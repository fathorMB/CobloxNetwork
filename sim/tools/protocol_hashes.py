CHAIN_ID = bytes(32)

DOMAINS = {
    "enrollment_parameters": b"coblox-enrollment-parameter-set-v0\x00",
    "reward_policy": b"coblox-reward-policy-v0\x00",
    "hosting_rate_card": b"coblox-hosting-rate-card-v0\x00",
    "consensus_parameters": b"coblox-consensus-parameters-v0\x00",
}

README = (
    pathlib.Path(__file__).resolve().parents[2] / "docs" / "protocol" / "README.md"
)

# The row of the registry table that publishes each value, by its `Hash` cell.
REGISTRY_ROWS = {
    "enrollment_parameters": "`parameter_set_hash`",
    "reward_policy": "`policy_hash`",
    "hosting_rate_card": "`hosting_rate_card_hash`",
    "consensus_parameters": "`consensus_parameters_hash`",
    "app_leaf": "`app_leaf`",
    "account_key_app": "`account_key` (app)",
}


def read_registry() -> dict[str, str]:
    """Read the expected values out of the published table.

    A missing row is a hard error rather than a skipped check: the whole point
    of reading the document is that this tool cannot silently keep asserting a
    value the document no longer publishes.
    """
    text = README.read_text(encoding="utf-8")
    published: dict[str, str] = {}
    for key, cell in REGISTRY_ROWS.items():
        pattern = re.compile(
            r"^\| " + re.escape(cell) + r" \| [^|]+ \| `(sha256:[0-9a-f]{64})` \|$",
            re.MULTILINE,
        )
        match = pattern.search(text)
        if match is None:
            raise SystemExit(
                f"docs/protocol/README.md publishes no registry row for {cell!r}; "
                f"this tool refuses to assert a value the document does not carry"
            )
        published[key] = match.group(1)
    return published


PUBLISHED = read_registry()

