def reward_body(availability: str) -> dict[str, str]:
    body = {k: "1" for k in REWARD_BODY_KEYS}
    body["availability_microtokens_per_unit"] = availability
    body["publisher_reward_cap_denominator"] = "2"
    body["validator_eligibility_min_issuers"] = "2"
    return body


def jcs(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


def document_hash(kind: str, body: dict) -> str:
    unsigned = {
        "schema_version": "0.1",
        "document_kind": kind,
        "network_id": "fixture",
        "chain_id": "sha256:" + CHAIN_ID.hex(),
        "sequence": "1",
        "activation_height": "1",
        "body": body,
    }
    digest = hashlib.sha256(DOMAINS[kind] + CHAIN_ID + jcs(unsigned)).hexdigest()
    return "sha256:" + digest


def sha(*parts: bytes) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(part)
    return "sha256:" + digest.hexdigest()


def u64be(value: int) -> bytes:
    return value.to_bytes(8, "big")


# --- APP-0, the fixture added for [DEBT-012] --------------------------------
#
# "`APP-0` is an **app** account in state `suspended`, for `app_id` `99`
# repeated 32 bytes, with `balance_microtokens` 1, `account_nonce` 1 and
# `suspension_effective_epoch` 1; its `lifecycle_u8` is therefore `0x03`".
APP0_APP_ID = bytes([0x99]) * 32
APP0_BALANCE = 1
APP0_NONCE = 1
APP0_SUSPENSION_EPOCH = 1
LIFECYCLE_SUSPENDED = 0x03

# Published before this pass and untouched by it, so they are what validates
# the tagged-tree method before it is used on a new value.
REVOCATION_NODE_ID = b"cblx1revokedfixture"
REVOCATION_EFFECTIVE_HEIGHT = 50


def app0_account_key() -> bytes:
    return hashlib.sha256(
        b"coblox-account-key-v0\x00" + b"\x01" + APP0_APP_ID
    ).digest()


def report(label: str, computed: str, published: str) -> bool:
    ok = computed == published
    print(f"  {label:<28} {'MATCH' if ok else 'MISMATCH'}")
    print(f"    published {published}")
    print(f"    computed  {computed}")
    return ok


def main() -> int:
    ok = True

    print("Governed protocol documents. None of the four changed in this pass,")
    print("so all four are method validation:")
    for kind, body in (
        ("enrollment_parameters", ENROLLMENT_BODY),
        ("hosting_rate_card", HOSTING_BODY),
        ("consensus_parameters", CONSENSUS_BODY),
        ("reward_policy", reward_body("0")),
    ):
        ok &= report(kind, document_hash(kind, body), PUBLISHED[kind])

    print()
    print("The reward fixture with the pre-[ADR-010] availability tariff, for")
    print("comparison - this is the shape the validity rule of [ADR-010] forbids:")
    print(f"    availability=1 -> {document_hash('reward_policy', reward_body('1'))}")

    print()
    print("Tagged trees. Method validation on the two values published before")
    print("this pass and untouched by it:")
    ok &= report(
        "empty revocation_root H(0x33)",
        sha(b"\x33"),
        "sha256:4e07408562bedb8b60ce05c1decfe3ad16b72230967de01f640b7e4729b49fce",
    )
    ok &= report(
        "revocation_leaf REVL-0",
        sha(
            b"\x30",
            len(REVOCATION_NODE_ID).to_bytes(4, "big"),
            REVOCATION_NODE_ID,
            u64be(REVOCATION_EFFECTIVE_HEIGHT),
        ),
        "sha256:7fb1f4024627c413cbf70b49a390b6d31778e667e86042864c4bed107cd52497",
    )

    print()
    print("The fixture this pass added, computed with that validated method")
    print("from the bytes the document now carries:")
    account_key = app0_account_key()
    ok &= report(
        "account_key (app) APP-0",
        "sha256:" + account_key.hex(),
        PUBLISHED["account_key_app"],
    )
    ok &= report(
        "app_leaf APP-0",
        sha(
            b"\x13",
            account_key,
            u64be(APP0_BALANCE),
            u64be(APP0_NONCE),
            bytes([LIFECYCLE_SUSPENDED]),
            u64be(APP0_SUSPENSION_EPOCH),
        ),
        PUBLISHED["app_leaf"],
    )

    print()
    print("The same leaf under the encodings the document does NOT use, so the")
    print("choice is visible as a choice and not as an accident:")
    for name, byte in (
        ("reserved 0x00 (invalid)", 0x00),
        ("provisional pre-[DEBT-012] suspended = 2", 0x02),
    ):
        print(
            f"    {name:<42} "
            + sha(
                b"\x13",
                account_key,
                u64be(APP0_BALANCE),
                u64be(APP0_NONCE),
                bytes([byte]),
                u64be(APP0_SUSPENSION_EPOCH),
            )
        )

    print()
    print(f"every published value reproduced: {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


