"""Recompute published Coblox hashes from the bytes the documents actually carry.

Versioned because [REVIEW-014] RF-007 found the transcript of [SPEC-009] citing
`scratch/*.py` scripts that were never in the tree: evidence nobody else can
re-run is not evidence.

Method, from `docs/protocol/README.md` §"Hash preimage registry":

    <kind>_hash = H(domain || chain_id_32 || JCS(UnsignedProtocolDocument))
    app_leaf    = H(0x13 || account_key || u64be(balance) || u64be(nonce)
                         || lifecycle_u8 || u64be(suspension_effective_epoch))

`H` is SHA-256 and `JCS` is RFC 8785 canonical JSON. Every `PD-0` body is a flat
object of ASCII keys and string values, for which JCS reduces to sorted keys,
no whitespace, and minimal escaping — which is what `json.dumps` produces with
`sort_keys=True` and compact separators.

    python sim/tools/protocol_hashes.py

**The expected values are read from `docs/protocol/README.md`, not copied into
this file.** They used to be copied, and that is how [SPEC-009] shipped a stale
constant that made this tool report a mismatch which did not exist — the false
positive [ADR-012] cites when it requires a guard to be proved in the negative.
A tool that carries its own copy of the oracle can disagree with the oracle
while looking authoritative. The `coblox-core` conformance suite still keeps a
hand transcription, and that one is deliberate for the opposite reason: a suite
whose expectation is generated by the implementation under test asserts nothing.
`sim/tools/published_artifacts.py` check C5 is what keeps the transcription and
the document from drifting apart.

Each section validates the method on values this pass did **not** change before
reporting the ones it did, which is the discipline `GATE-FIXTURES-RECOMPUTED`
exists to enforce: a procedure that cannot reproduce an untouched value is not
evidence for a touched one.
"""

from __future__ import annotations

