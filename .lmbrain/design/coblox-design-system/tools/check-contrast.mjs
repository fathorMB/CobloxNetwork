#!/usr/bin/env node
/**
 * GATE-CONTRAST (SPEC-003): verify every declared text/background and non-text
 * pairing against WCAG 2.1 contrast minima, for every theme.
 *
 * Algorithm: WCAG 2.1 relative luminance (sRGB, ITU-R BT.709 coefficients) and
 * the (L1 + 0.05) / (L2 + 0.05) contrast-ratio formula, as defined in
 * https://www.w3.org/TR/WCAG21/#dfn-contrast-ratio and #dfn-relative-luminance.
 *
 * Usage:
 *   node design/tools/check-contrast.mjs            # table to stdout, exit 1 on any failure
 *   node design/tools/check-contrast.mjs --write    # also write design/tokens/CONTRAST.md
 *
 * Exit code 0 = every declared pair meets its threshold.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = resolve(here, '../tokens/tokens.json');
const PAIRS = resolve(here, '../tokens/contrast-pairs.json');
const OUT = resolve(here, '../tokens/CONTRAST.md');

const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'));
const declared = JSON.parse(readFileSync(PAIRS, 'utf8'));

function primitive(path) {
  const v = path.split('.').reduce((n, k) => (n == null ? n : n[k]), tokens.primitive);
  if (typeof v !== 'string') throw new Error(`Unknown primitive: {${path}}`);
  return v;
}

/** Resolve a semantic token name in a given theme down to a literal value. */
function resolve_(theme, name) {
  const raw = tokens.semantic[theme][name];
  if (raw === undefined) throw new Error(`Token "${name}" is not defined in theme "${theme}"`);
  return raw.replace(/\{([^}]+)\}/g, (_, p) => primitive(p));
}

function parseHex(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) throw new Error(`Only opaque 6-digit hex colors can be contrast-checked, got "${hex}"`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** WCAG 2.1 relative luminance. */
function luminance(hex) {
  const [r, g, b] = parseHex(hex).map((c) => {
    const s = c / 255;
    return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function ratio(fg, bg) {
  const a = luminance(fg);
  const b = luminance(bg);
  const [hi, lo] = a > b ? [a, b] : [b, a];
  return (hi + 0.05) / (lo + 0.05);
}

const thresholds = declared.$meta.thresholds;
const themes = Object.keys(tokens.semantic).filter((k) => !k.startsWith('_'));

const rows = [];
let failures = 0;

for (const theme of themes) {
  for (const pair of declared.pairs) {
    const fgValue = resolve_(theme, pair.fg);
    const bgValue = resolve_(theme, pair.bg);
    const r = ratio(fgValue, bgValue);
    const min = thresholds[pair.type];
    if (min === undefined) throw new Error(`Unknown pair type "${pair.type}"`);
    // Round the way a reporting tool does, then compare, so the printed number
    // and the verdict can never disagree.
    const shown = Math.floor(r * 100) / 100;
    const pass = shown >= min;
    if (!pass) failures += 1;
    rows.push({ theme, ...pair, fgValue, bgValue, ratio: shown, min, pass });
  }
}

const pad = (s, n) => String(s).padEnd(n);
console.log(`WCAG 2.1 contrast check — ${rows.length} declared pairs across themes: ${themes.join(', ')}\n`);
for (const theme of themes) {
  console.log(`[${theme}]`);
  for (const row of rows.filter((r) => r.theme === theme)) {
    console.log(
      `  ${row.pass ? 'PASS' : 'FAIL'}  ${pad(row.ratio.toFixed(2) + ':1', 9)} (min ${row.min.toFixed(1)})  ` +
        `${pad(row.fg + ' ' + row.fgValue, 46)} on ${pad(row.bg + ' ' + row.bgValue, 46)} ${row.type}`
    );
  }
  console.log('');
}

if (process.argv.includes('--write')) {
  const lines = [
    '<!-- GENERATED by design/tools/check-contrast.mjs — do not edit by hand. -->',
    '',
    '# Contrast verification (GATE-CONTRAST)',
    '',
    `Tool: \`design/tools/check-contrast.mjs\` — WCAG 2.1 relative-luminance formula`,
    '([W3C definition](https://www.w3.org/TR/WCAG21/#dfn-contrast-ratio)).',
    '',
    `Thresholds: normal text **${thresholds.text}:1** (WCAG 1.4.3 AA), non-text UI components and`,
    `meaningful graphics **${thresholds['non-text']}:1** (WCAG 1.4.11).`,
    '',
    `Result: **${rows.length - failures}/${rows.length} pass, ${failures} fail.**`,
    '',
    declared.$meta.note,
    ''
  ];
  for (const theme of themes) {
    lines.push(`## Theme: ${theme}`, '');
    lines.push('| Foreground | Background | Ratio | Min | Verdict | Usage |');
    lines.push('| --- | --- | ---: | ---: | --- | --- |');
    for (const row of rows.filter((r) => r.theme === theme)) {
      lines.push(
        `| \`${row.fg}\` ${row.fgValue} | \`${row.bg}\` ${row.bgValue} | ${row.ratio.toFixed(2)}:1 | ${row.min.toFixed(1)} | ${row.pass ? 'PASS' : '**FAIL**'} | ${row.usage} |`
      );
    }
    lines.push('');
  }
  lines.push('## Declared exemptions', '');
  for (const e of declared.exempt) {
    lines.push(`- **${e.tokens.map((t) => `\`${t}\``).join(', ')}** — ${e.reason}`);
    if (e['compensating-control']) lines.push(`  - Compensating control: ${e['compensating-control']}`);
  }
  lines.push('');
  writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log(`Wrote ${OUT}`);
}

console.log(failures === 0 ? `RESULT: all ${rows.length} declared pairs meet WCAG AA.` : `RESULT: ${failures} of ${rows.length} pairs FAIL.`);
process.exit(failures === 0 ? 0 : 1);
